"""Render the Mosaico launcher and Glimdock (actual firmware UI) on the host.

  python3 host/render.py [--snapshot SNAPSHOT.json] [--radius 80] [--output DIR]

Needs a Glimdock checkout (GLIMDOCK_DIR, https://github.com/gkostadinov/glimdock)
for its native preview's fixture generator and demo snapshot; uses the device's LVGL
Kconfig and the shell's frame geometry. PNGs show the panel's rounded corners
(pixels outside them are dimmed), so clipped content is visible at a glance.
"""
import argparse
import importlib.util
import json
import math
import os
import struct
import subprocess
import sys
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIRMWARE = Path(os.environ.get('GLIMDOCK_FIRMWARE_DIR') or HERE.parent / 'third_party/glimdock/firmware')
GLIMDOCK = Path(os.environ.get('GLIMDOCK_DIR', ''))
NATIVE = GLIMDOCK / 'tools/native-preview'


def png(ppm: Path, radius: int):
    header, size, _, raw = ppm.read_bytes().split(b'\n', 3)
    width, height = map(int, size.split())
    pixels = bytearray(raw)
    c = radius
    for y in range(height):
        for x in range(width):
            dx = max(c - x, x - (width - 1 - c), 0)
            dy = max(c - y, y - (height - 1 - c), 0)
            if c and dx > 0 and dy > 0 and math.hypot(dx, dy) > c:
                i = (y * width + x) * 3
                pixels[i:i + 3] = bytes(v // 5 for v in pixels[i:i + 3])  # hidden by the bezel
    rows = b''.join(b'\0' + bytes(pixels[y * width * 3:(y + 1) * width * 3]) for y in range(height))

    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)

    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0))
    data += chunk(b'IDAT', zlib.compress(rows, 6)) + chunk(b'IEND', b'')
    ppm.with_suffix('.png').write_bytes(data)
    ppm.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--snapshot', type=Path, default=GLIMDOCK / 'examples/snapshots/host.json')
    parser.add_argument('--radius', type=int, default=80)
    parser.add_argument('--output', type=Path, default=HERE.parent / 'build-host/captures')
    parser.add_argument('--build-dir', type=Path, default=HERE.parent / 'build-host')
    parser.add_argument('--home-fixtures', type=Path, help='saved hub API responses (catalog.json, devices.json, ...)')
    args = parser.parse_args()
    if not (NATIVE / 'render.py').exists():
        sys.exit('Set GLIMDOCK_DIR to a Glimdock checkout (https://github.com/gkostadinov/glimdock)')
    spec = importlib.util.spec_from_file_location('native_render', NATIVE / 'render.py')
    native = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(NATIVE))
    spec.loader.exec_module(native)
    args.build_dir.mkdir(parents=True, exist_ok=True)
    native.fixture(json.loads(args.snapshot.read_text()), args.build_dir / 'fixture.h')
    # Glimdock's demo data, taken from the firmware's own generator.
    network = (FIRMWARE / 'src/network.cpp').read_text()
    start = network.index('void makeDemo(Snapshot &s){')
    demo = network[start:network.index('\nbool readOperations', start)]
    (args.build_dir / 'demo_snapshot.cpp').write_text(
        '// Generated by render.py from firmware/src/network.cpp (makeDemo).\n'
        '#include <math.h>\n#include <time.h>\n#include "model.h"\n' + demo + '\n')
    for command in (['cmake', '-S', str(HERE), '-B', str(args.build_dir), '-DCMAKE_BUILD_TYPE=Release'],
                    ['cmake', '--build', str(args.build_dir), '-j', '8']):
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode:
            print(result.stdout[-6000:], result.stderr[-6000:], sep='\n')
            sys.exit(result.returncode)
    result = subprocess.run([str(args.build_dir / 'mosaico-preview'), str(args.output), str(args.radius)] + ([str(args.home_fixtures)] if args.home_fixtures else []),
                            capture_output=True, text=True)
    print(result.stdout, result.stderr, sep='')
    if result.returncode:
        sys.exit(result.returncode)
    for ppm in sorted(args.output.glob('*.ppm')):
        png(ppm, args.radius)
    print('captures in', args.output)


if __name__ == '__main__':
    main()
