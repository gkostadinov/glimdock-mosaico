"""Convert Swifty Home's icons.lua (24x24 stroke polylines) to home_icons.h.

  python3 lua_icons_to_c.py icons.lua home_icons.h

icons.lua is generated by Glimdock's mosaico/tools/svg_icons.py from the
web app's SVG sprite; this keeps the native app on the same geometry.
"""

import re
import sys

source, target = sys.argv[1], sys.argv[2]
text = open(source, encoding="utf-8").read()
icons = []
for name, body in re.findall(r'\["([a-z0-9_]+)"\]=\{(.*?)\}\s*,?\s*\n', text):
    paths = [[float(v) for v in p.split(",") if v.strip()] for p in re.findall(r"\{([^{}]*)\}", body)]
    icons.append((name, [p for p in paths if len(p) >= 4]))
icons.sort()
out = [
    "// Generated by tools/lua_icons_to_c.py from Swifty Home icons.lua; do not edit.",
    "#pragma once",
    "#include <stddef.h>",
    "#include <stdint.h>",
    "",
    "namespace home_icons {",
    "struct Path { const float *xy; uint16_t points; };",
    "struct Icon { const char *name; const Path *paths; uint8_t count; };",
    "",
]
for i, (name, paths) in enumerate(icons):
    for j, p in enumerate(paths):
        out.append(f"inline constexpr float i{i}_{j}[] = {{" + ",".join(f"{float(v)!r}f" for v in p) + "};")
    out.append(
        f"inline constexpr Path i{i}[] = {{"
        + ",".join(f"{{i{i}_{j},{len(p) // 2}}}" for j, p in enumerate(paths))
        + "};"
    )
out.append("inline constexpr Icon all[] = {")
out += [f'  {{"{name}", i{i}, {len(paths)}}},' for i, (name, paths) in enumerate(icons)]
out += [
    "};",
    "inline const Icon *find(const char *name) {",
    "  for (const auto &icon : all) { const char *a = icon.name, *b = name;",
    "    while (*a && *a == *b) { ++a; ++b; }",
    "    if (*a == *b) return &icon; }",
    "  return nullptr;",
    "}",
    "}  // namespace home_icons",
    "",
]
open(target, "w", encoding="utf-8").write("\n".join(out))
print(len(icons), "icons:", " ".join(n for n, _ in icons))
